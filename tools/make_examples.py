def main() -> None:
    pending = common.ROOT / "data" / "cases" / "pending"
    out = common.ensure_dir(common.ROOT / "data" / "cases" / "examples")
    for case_id, mode, label, answer, structured, eval_block, report in EXAMPLES:
        fp = pending / f"{case_id}.json"
        if not fp.exists():
            print(f"!! нет кейса {case_id} — пропуск")
            continue
        case = common.read_json(fp)
        case["label"] = label
        case["gold"]["answer"] = answer
        case["gold"]["answer_structured"] = {**structured, "evidence_refs": structured.get("evidence_refs", [])}
        case["gold"]["report_markdown"] = report
        case["gold"]["checklist"] = {"must_not_claim": eval_block["forbidden_claims"], "needs_verification": []}
        case["eval"] = eval_block
        case["annotation"] = {"annotator_id": "example", "annotator_role": "эталонный пример",
                              "annotated_at": common.now_iso(), "time_spent_min": 45,
                              "double_annotated": False, "reviewer_id": "example",
                              "review_status": "accepted", "review_comments": "Эталонный пример качества разметки."}
        # probe-ответы кратко
        for pq in case.get("probe_questions", []):
            pq["answer"] = {"observations": "см. gold.answer_structured.observations",
                            "causes": "; ".join(p["text"] for p in structured["probable_causes"]),
                            "limitations": "; ".join(structured["limitations"])}.get(pq["id"])
        common.write_json(out / f"{case_id}.json", case)
        print(f"✓ {case_id} → examples/")


if __name__ == "__main__":
    main()
