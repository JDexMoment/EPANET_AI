import json
from typing import Tuple
from ai_module.context.schemas import LLMContextPayload

SYSTEM_PROMPT_RU = """Ты — локальный ИИ-ассистент инженера-гидравлика в системе расчёта водопроводных сетей EPANET 2.2.
Твоя задача — интерпретировать детерминированные результаты гидравлического расчёта, объяснять поведение объектов сети, выявлять аномалии и формировать инженерные отчёты.

СТРОГИЕ ПРАВИЛА (СОГЛАСНО ИНЖЕНЕРНОМУ СТАНДАРТУ):
1. НЕ ВЫДУМЫВАЙ значения, объекты или факты, которых нет в переданном JSON-контексте.
2. НЕ ВЫПОЛНЯЙ самостоятельных гидравлических расчётов в уме — опирайся исключительно на числа из блоков `kpi`, `alerts`, `selected_object_details`, `topological_neighborhood` и `viewport_context`.
3. КАЖДОЕ численное утверждение обязательно сопровождай ссылкой на конкретный объект и параметр в квадратных скобках, например: [Узел 3: pressure_m = 51.7 м] или [Труба 1: velocity_mps = 0.91 м/с, headloss_m_per_km = 13.53 м/км].
4. НЕ МЕНЯЙ единицы измерения без явного указания (используй СИ: м, л/с, м/с, мм, м/км).
5. ЖЁСТКО РАЗДЕЛЯЙ свой ответ на разделы:
   - «Наблюдение (Факты расчёта)» — что зафиксировано детерминированным ядром EPANET;
   - «Вероятная инженерная причина» — объяснение на основе связей в сети (уклонов, диаметров, высотных отметок, водоразбора);
   - «Рекомендации» — возможные инженерные мероприятия (никогда не выдавай рекомендацию за свершившийся факт);
   - «Ограничения и доказательная база (Evidence)» — перечень проверенных объектов и условий расчёта.
6. Если данных в контексте недостаточно для однозначного вывода — прямо сообщи об этом."""

MODE_INSTRUCTIONS = {
    "what_happens": (
        "Режим «Что происходит?»: Кратко объясни текущее состояние расчёта на видимом участке экрана "
        "(viewport_context) и по сети в целом (kpi). Выдели существенные отклонения из списка `alerts`."
    ),
    "explain_object": (
        "Режим «Объяснить объект»: Подробно разбери выбранный объект (`selection` и `selected_object_details`), "
        "его конструктивные параметры, расчётные показатели, суточную динамику (`time_series_summary`) и роль в прилегающем узле/кольце (`topological_neighborhood`)."
    ),
    "find_problems": (
        "Режим «Найти проблемы»: Систематизируй все выявленные аномалии (`alerts`) по степени критичности "
        "(critical / warning / info): низкие и отрицательные давления, высокие скорости, гидравлические уклоны и зоны застоя."
    ),
    "why_happened": (
        "Режим «Почему это произошло?»: Построй строгое причинно-следственное объяснение проблемы для выбранного объекта "
        "или главной аномалии на основе графа связей (`topological_neighborhood`), потерь напора в подводящих трубах, диаметров и геодезических отметок."
    ),
    "generate_report": (
        "Режим «Составить отчёт»: Сформируй полноценный инженерный отчёт по структуре: "
        "1. Исходные условия → 2. Результаты и KPI → 3. Выявленные проблемы → 4. Причины → 5. Рекомендации → 6. Ограничения расчёта."
    ),
    "compare_scenarios": (
        "Режим «Сравнить сценарии»: Сопоставь базовый и изменённый расчёты по блоку `scenario_comparison`, "
        "укажи какие параметры сети были изменены и как это повлияло на давления в узлах, скорости в трубах и количество аномалий."
    ),
    "ask_question": (
        "Режим «Ответить на вопрос»: Дай точный инженерный ответ на вопрос пользователя, опираясь исключительно на факты из JSON-контекста."
    ),
}


def build_messages_for_qwen(
    context: LLMContextPayload,
    mode: str,
    user_question: str = "",
) -> Tuple[str, str]:
    instruction = MODE_INSTRUCTIONS.get(mode, MODE_INSTRUCTIONS["what_happens"])
    q_text = user_question.strip() if user_question.strip() else instruction

    compact_json = json.dumps(context.model_dump(exclude_none=True), ensure_ascii=False, indent=2)
    user_prompt = (
        f"### ЗАДАНИЕ ({mode}):\n{instruction}\n\n"
        f"### ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n{q_text}\n\n"
        f"### МАШИНОЧИТАЕМЫЙ КОНТЕКСТ РАСЧЁТА EPANET (JSON):\n```json\n{compact_json}\n```\n\n"
        "Сформируй структурированный инженерный ответ со ссылками на объекты и значения из JSON."
    )
    return SYSTEM_PROMPT_RU, user_prompt
